// components/shared/study-material.tsx — the printable document for a
// teacher's study material (flashcard deck or mind map).
//
// One component renders both the on-screen preview and the printed sheet,
// so the two cannot drift. It is deliberately plain: black on white, no
// shadows, no rounded corners on paper — a printed mind map is a worksheet,
// not a UI.

export interface Flashcard {
    front: string;
    back: string;
}

export interface FlashcardsContent {
    cards: Flashcard[];
}

export interface MindmapBranch {
    title: string;
    children: string[];
}

export interface MindmapContent {
    root: string;
    branches: MindmapBranch[];
}

export type StudyMaterialKind = "FLASHCARDS" | "MINDMAP";

export interface MaterialMeta {
    title: string;
    kind: StudyMaterialKind;
    className?: string | null;
    subjectName?: string | null;
    sourceName?: string | null;
    createdAt?: string | null;
}

export interface Letterhead {
    schoolName: string;
    address?: string;
    phone?: string;
    email?: string;
}

/**
 * The printed sheet.
 *
 * Flashcards print as a two-column table: the question on the left, a blank
 * answer box on the right, so the teacher can cut them into separate cards.
 * The mind map prints as an indented outline rooted at the topic, which stays
 * legible in black and white and does not depend on a tree layout engine.
 */
export function StudyMaterialDocument({
    kind,
    content,
    meta,
    letterhead,
    answers,
}: {
    kind: StudyMaterialKind;
    content: FlashcardsContent | MindmapContent;
    meta: MaterialMeta;
    letterhead: Letterhead;
    /** FLASHCARDS: include the answer key (the teacher's copy). */
    answers?: boolean;
}) {
    return (
        <div className="mx-auto w-full max-w-3xl bg-white p-8 text-black print:p-0">
            <header className="mb-6 border-b-2 border-black pb-3">
                <p className="text-[10px] font-black uppercase tracking-[0.2em]">
                    {letterhead.schoolName}
                </p>
                {letterhead.address ? (
                    <p className="text-[9px] text-neutral-700">{letterhead.address}</p>
                ) : null}
                <h1 className="mt-2 text-xl font-black uppercase tracking-tight">
                    {meta.title}
                </h1>
                <p className="mt-1 text-[10px] text-neutral-700">
                    {[
                        kind === "FLASHCARDS" ? "Flashcards" : "Mind map",
                        meta.className,
                        meta.subjectName,
                        meta.sourceName,
                    ]
                        .filter(Boolean)
                        .join(" · ")}
                </p>
            </header>

            {kind === "FLASHCARDS" ? (
                <FlashcardsSheet
                    cards={(content as FlashcardsContent).cards}
                    answers={answers}
                />
            ) : (
                <MindmapSheet content={content as MindmapContent} />
            )}

            <footer className="mt-8 border-t border-neutral-300 pt-2 text-[9px] text-neutral-600">
                Generated by Guzia Bilateral High School portal · {new Date().toLocaleDateString()}
            </footer>
        </div>
    );
}

function FlashcardsSheet({
    cards,
    answers,
}: {
    cards: Flashcard[];
    answers?: boolean;
}) {
    return (
        <table className="w-full border-collapse text-left">
            <thead>
                <tr>
                    <th className="w-8 border border-black/60 px-2 py-1.5 text-[9px] font-black uppercase tracking-wider">
                        #
                    </th>
                    <th className="border border-black/60 px-2 py-1.5 text-[9px] font-black uppercase tracking-wider">
                        Question
                    </th>
                    <th className="w-1/2 border border-black/60 px-2 py-1.5 text-[9px] font-black uppercase tracking-wider">
                        {answers ? "Answer" : "Your answer"}
                    </th>
                </tr>
            </thead>
            <tbody>
                {cards.map((card, i) => (
                    <tr key={i} className="break-inside-avoid align-top">
                        <td className="border border-black/60 px-2 py-2 text-[10px] font-bold">
                            {i + 1}
                        </td>
                        <td className="border border-black/60 px-2 py-2 text-xs font-semibold">
                            {card.front}
                        </td>
                        <td className="border border-black/60 px-2 py-2 text-xs">
                            {answers ? (
                                card.back
                            ) : (
                                <span className="block min-h-10 text-neutral-400">
                                    {/* blank writing space */}
                                </span>
                            )}
                        </td>
                    </tr>
                ))}
            </tbody>
        </table>
    );
}

function MindmapSheet({ content }: { content: MindmapContent }) {
    return (
        <div>
            <h2 className="mb-3 border-l-4 border-black pl-3 text-base font-black uppercase tracking-tight">
                {content.root}
            </h2>
            <ul className="space-y-3">
                {content.branches.map((branch, bi) => (
                    <li key={bi} className="break-inside-avoid">
                        <p className="text-xs font-black uppercase tracking-wide">
                            {branch.title}
                        </p>
                        <ul className="mt-1 list-disc space-y-1 pl-6">
                            {branch.children.map((child, ci) => (
                                <li key={ci} className="text-xs leading-relaxed">
                                    {child}
                                </li>
                            ))}
                        </ul>
                    </li>
                ))}
            </ul>
        </div>
    );
}
